    public static class ResourceModuleTableGenerator
    {
        private const string Header = "// Generated by ResourceModuleTableGenerator. Do not edit.\n";
        private const string OwnerHeader = "// Source GUID: ";
        private const string HashHeader = "// Body SHA256: ";
        private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false);
        private static readonly Regex Identifier = new Regex("\\A[A-Za-z_][A-Za-z0-9_]*\\z");
        private static readonly HashSet<string> ReservedMembers = new HashSet<string>(
            ("Id GetName RecordAllResourceInfos GetResource AddResourceInfo LoadResources UnloadResources " +
             "Shutdown GetType ToString Equals GetHashCode ReferenceEquals MemberwiseClone Finalize").Split(' '), StringComparer.Ordinal);
        private static readonly HashSet<string> Keywords = new HashSet<string>(
            ("abstract as base bool break byte case catch char checked class const continue decimal " +
             "default delegate do double else enum event explicit extern false finally fixed float for " +
             "foreach goto if implicit in int interface internal is lock long namespace new null object " +
             "operator out override params private protected public readonly ref return sbyte sealed short " +
             "sizeof stackalloc static string struct switch this throw true try typeof uint ulong " +
             "unchecked unsafe ushort using virtual void volatile while add alias and ascending async " +
             "await by descending dynamic equals file from get global group init into join let managed " +
             "nameof nint not notnull nuint on or orderby partial record remove required scoped select " +
             "set unmanaged value var when where with yield __arglist __makeref __reftype __refvalue").Split(' '), StringComparer.Ordinal);

        public static bool Generate(ResourceModuleTable table)
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling)
            {
                Debug.LogError("Generate resource modules outside Play Mode, after compilation finishes.", table);
                return false;
            }

            if (!Validate(table, out string outputPath, out string content, out string error))
            {
                Debug.LogError(error, table);
                return false;
            }

            string temporaryPath = null;

            try
            {
                if (File.Exists(outputPath))
                {
                    if (!IsOwnedAndUnmodified(outputPath, AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table)), out error))
                    {
                        Debug.LogError(Describe(table) + ": " + error, table);
                        return false;
                    }

                    if (Read(outputPath) == content)
                    {
                        Debug.Log("Resource module table is already up to date: " + outputPath, table);
                        return true;
                    }
                }

                Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
                temporaryPath = outputPath + "." + Guid.NewGuid().ToString("N") + ".tmp";
                File.WriteAllText(temporaryPath, content, Utf8);

                if (File.Exists(outputPath))
                {
                    File.Replace(temporaryPath, outputPath, null);
                }
                else
                {
                    File.Move(temporaryPath, outputPath);
                }

                AssetDatabase.ImportAsset(outputPath);
                Debug.Log("Generated Resource module table: " + outputPath, table);
                return true;
            }
            catch (Exception exception)
            {
                Debug.LogError(Describe(table) + ": could not write generated code. " + exception.Message, table);
                return false;
            }
            finally
            {
                if (temporaryPath != null && File.Exists(temporaryPath))
                {
                    File.Delete(temporaryPath);
                }
            }
        }

        public static bool ValidateGenerated(ResourceModuleTable table, out string error)
        {
            if (!Validate(table, out string outputPath, out string content, out error))
            {
                return false;
            }

            try
            {
                if (!File.Exists(outputPath))
                {
                    error = Describe(table) + ": generated code is missing. Click Validate and Generate.";
                    return false;
                }

                if (!IsOwnedAndUnmodified(outputPath, AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table)), out error))
                {
                    error = Describe(table) + ": " + error;
                    return false;
                }

                if (Read(outputPath) != content)
                {
                    error = Describe(table) + ": generated code is out of date. Click Validate and Generate.";
                    return false;
                }

                return ValidateOutputLocations(table, out error);
            }
            catch (Exception exception)
            {
                error = Describe(table) + ": could not read generated code. " + exception.Message;
                return false;
            }
        }

        public static bool Validate(ResourceModuleTable table, out string outputPath, out string content, out string error)
        {
            outputPath = null;
            content = null;
            error = null;
            string source = Describe(table);

            try
            {
                string assetPath = AssetDatabase.GetAssetPath(table);
                const string folder = "/Editor/Tables/ResourceModules/";
                int folderIndex = assetPath.IndexOf(folder, StringComparison.Ordinal);

                if (table == null || !assetPath.StartsWith("Assets/", StringComparison.Ordinal) || folderIndex < 0 ||
                    !assetPath.EndsWith(".asset", StringComparison.Ordinal) ||
                    assetPath.Substring(folderIndex + folder.Length).Contains("/"))
                {
                    throw new InvalidOperationException("save this table at <game root>/Editor/Tables/ResourceModules/<name>.asset inside Assets.");
                }

                string gameRoot = assetPath.Substring(0, folderIndex);

                if (gameRoot == "Assets/Framework" || gameRoot.StartsWith("Assets/Framework/", StringComparison.Ordinal))
                {
                    throw new InvalidOperationException("save game configuration in your own game folder, outside Assets/Framework.");
                }

                if (!ValidIdentifier(table.ClassName) || ReservedMembers.Contains(table.ClassName))
                {
                    throw new InvalidOperationException("ClassName must be a C# identifier and cannot be a keyword or generated/inherited member name.");
                }

                if (!string.IsNullOrEmpty(table.Namespace) && !ValidDottedIdentifier(table.Namespace))
                {
                    throw new InvalidOperationException("Namespace must contain C# identifiers separated by dots, or be empty.");
                }

                if (string.IsNullOrWhiteSpace(table.ModuleId))
                {
                    throw new InvalidOperationException("ModuleId must not be empty, for example MyGame.Main.");
                }

                foreach (string guid in AssetDatabase.FindAssets("t:ResourceModuleTable"))
                {
                    var other = AssetDatabase.LoadAssetAtPath<ResourceModuleTable>(AssetDatabase.GUIDToAssetPath(guid));

                    if (other == null || other == table)
                    {
                        continue;
                    }

                    if (other.ModuleId == table.ModuleId)
                    {
                        throw new InvalidOperationException("ModuleId is already used by " + AssetDatabase.GetAssetPath(other));
                    }

                    CheckTypeName(table, other.Namespace, other.ClassName, AssetDatabase.GetAssetPath(other));
                }

                // UI and resource tables share the game's Generated directory and C# namespace.
                foreach (string guid in AssetDatabase.FindAssets("t:UITable"))
                {
                    string path = AssetDatabase.GUIDToAssetPath(guid);
                    var other = AssetDatabase.LoadAssetAtPath<global::UI.Editor.UITable>(path);

                    if (other != null)
                    {
                        CheckTypeName(table, other.Namespace, other.ClassName, path);
                    }
                }

                var settings = AddressableAssetSettingsDefaultObject.Settings;

                if (settings == null)
                {
                    throw new InvalidOperationException("Addressables settings are missing. Configure your game's content root once before generating.");
                }

                var assets = new List<AddressableAssetEntry>();
                settings.GetAllAssets(assets, false, group =>
                {
                    var schema = group.GetSchema<BundledAssetGroupSchema>();
                    return schema != null && schema.IncludeInBuild && schema.IncludeAddressInCatalog;
                });

                var rows = ReadRows(table);
                var names = new HashSet<string>(StringComparer.Ordinal);

                foreach (Row row in rows)
                {
                    if (!ValidIdentifier(row.Name) || ReservedMembers.Contains(row.Name) ||
                        row.Name == table.ClassName || !names.Add(row.Name))
                    {
                        throw new InvalidOperationException(row.Label + ": Name must be a unique ASCII C# identifier, not a keyword or generated/inherited member name: " + row.Name);
                    }

                    string path = AssetDatabase.GetAssetPath(row.Asset);

                    if (row.Asset == null || !AssetDatabase.Contains(row.Asset) || !path.StartsWith("Assets/", StringComparison.Ordinal))
                    {
                        throw new InvalidOperationException(row.Label + ": drag a saved asset from your game content folder.");
                    }

                    if (row.Type == ResourceType.GameObject &&
                        (!PrefabUtility.IsPartOfPrefabAsset(row.Asset) ||
                         !path.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase) ||
                         ((GameObject)row.Asset).transform.parent != null))
                    {
                        throw new InvalidOperationException(row.Label + ": Asset must be a saved prefab root.");
                    }

                    if (row.Type == ResourceType.Sprite && !AssetDatabase.IsMainAsset(row.Asset))
                    {
                        var importer = AssetImporter.GetAtPath(path) as TextureImporter;

                        if (importer == null || importer.spriteImportMode != SpriteImportMode.Single)
                        {
                            throw new InvalidOperationException(row.Label + ": only standalone Sprites and textures imported as Sprite (Single) are supported. Multiple sprites and atlas sub-assets need a distinct loading key and are not supported yet.");
                        }
                    }
                    else if (AssetDatabase.IsSubAsset(row.Asset))
                    {
                        throw new InvalidOperationException(row.Label + ": sub-assets are not supported by this resource table.");
                    }

                    string assetGuid = AssetDatabase.AssetPathToGUID(path);
                    string address = null;

                    foreach (AddressableAssetEntry asset in assets)
                    {
                        if (asset.guid != assetGuid || asset.AssetPath != path || string.IsNullOrWhiteSpace(asset.address))
                        {
                            continue;
                        }

                        if (address != null && address != asset.address)
                        {
                            throw new InvalidOperationException(row.Label + ": asset has multiple effective Addressables addresses: " + path);
                        }

                        address = asset.address;
                    }

                    if (address == null)
                    {
                        throw new InvalidOperationException(row.Label + ": asset has no loadable Addressables address. Move it under the configured game content root, or ask your programmer to check its group, Include in Build and Include Addresses in Catalog: " + path);
                    }

                    foreach (AddressableAssetEntry asset in assets)
                    {
                        if (asset.address == address && asset.guid != assetGuid)
                        {
                            throw new InvalidOperationException(row.Label + ": Addressables address is shared by another asset: " + address);
                        }
                    }

                    row.Address = address;
                }

                outputPath = gameRoot + "/Scripts/Generated/" + table.ClassName + ".g.cs";
                string body = BuildBody(table, rows);
                content = Header + OwnerHeader + AssetDatabase.AssetPathToGUID(assetPath) + "\n" +
                    HashHeader + Hash(body) + "\n\n" + body;
                return true;
            }
            catch (Exception exception)
            {
                error = source + ": " + exception.Message;
                return false;
            }
        }

        public static bool ValidateOutputLocations(ResourceModuleTable table, out string error)
        {
            string sourceGuid = table == null ? null : AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table));

            try
            {
                foreach (string file in Directory.EnumerateFiles("Assets", "*.g.cs", SearchOption.AllDirectories))
                {
                    string path = file.Replace('\\', '/');
                    string existing = Read(path);

                    if (!existing.StartsWith(Header, StringComparison.Ordinal))
                    {
                        continue;
                    }

                    string prefix = Header + OwnerHeader;
                    int end = existing.IndexOf('\n', prefix.Length);
                    string ownerGuid = existing.StartsWith(prefix, StringComparison.Ordinal) && end >= 0
                        ? existing.Substring(prefix.Length, end - prefix.Length) : "";

                    if (sourceGuid != null && ownerGuid != sourceGuid)
                    {
                        continue;
                    }

                    var owner = AssetDatabase.LoadAssetAtPath<ResourceModuleTable>(AssetDatabase.GUIDToAssetPath(ownerGuid));

                    if (owner == null)
                    {
                        error = "Resource module output has no source table. Remove obsolete output and its meta: " + path;
                        return false;
                    }

                    if (!Validate(owner, out string expectedPath, out _, out error))
                    {
                        return false;
                    }

                    if (path != expectedPath)
                    {
                        error = "Resource table moved or ClassName changed. Update callers, then remove obsolete output and its meta: " + path +
                            ". Current output belongs at " + expectedPath;
                        return false;
                    }
                }

                error = null;
                return true;
            }
            catch (Exception exception)
            {
                error = "Could not check resource module output locations: " + exception.Message;
                return false;
            }
        }

        private sealed class Row
        {
            public string Name;
            public UnityEngine.Object Asset;
            public ResourceType Type;
            public string Label;
            public string Address;
        }

        private static List<Row> ReadRows(ResourceModuleTable table)
        {
            var rows = new List<Row>();

            if (table.AudioClips == null || table.Prefabs == null || table.Sprites == null)
            {
                throw new InvalidOperationException("Resource lists must not be null.");
            }

            for (int index = 0; index < table.AudioClips.Count; index++)
            {
                var entry = table.AudioClips[index];
                rows.Add(new Row { Name = entry?.Name, Asset = entry?.Asset, Type = ResourceType.AudioClip, Label = "Audio Clips entry " + (index + 1) });
            }

            for (int index = 0; index < table.Prefabs.Count; index++)
            {
                var entry = table.Prefabs[index];
                rows.Add(new Row { Name = entry?.Name, Asset = entry?.Asset, Type = ResourceType.GameObject, Label = "Prefabs entry " + (index + 1) });
            }

            for (int index = 0; index < table.Sprites.Count; index++)
            {
                var entry = table.Sprites[index];
                rows.Add(new Row { Name = entry?.Name, Asset = entry?.Asset, Type = ResourceType.Sprite, Label = "Sprites entry " + (index + 1) });
            }

            return rows;
        }

        private static void CheckTypeName(ResourceModuleTable table, string otherNamespace, string otherClass, string path)
        {
            if (TypeNamesConflict(table.Namespace, table.ClassName, otherNamespace, otherClass))
            {
                throw new InvalidOperationException("Namespace/ClassName is already used by " + path);
            }
        }

        internal static bool TypeNamesConflict(string firstNamespace, string firstClass, string secondNamespace, string secondClass)
        {
            string first = string.IsNullOrEmpty(firstNamespace) ? firstClass : firstNamespace + "." + firstClass;
            string second = string.IsNullOrEmpty(secondNamespace) ? secondClass : secondNamespace + "." + secondClass;
            return first == second || secondNamespace == first || firstNamespace == second ||
                (!string.IsNullOrEmpty(secondNamespace) && secondNamespace.StartsWith(first + ".", StringComparison.Ordinal)) ||
                (!string.IsNullOrEmpty(firstNamespace) && firstNamespace.StartsWith(second + ".", StringComparison.Ordinal));
        }

        private static string BuildBody(ResourceModuleTable table, List<Row> rows)
        {
            var text = new StringBuilder();
            string indent = string.IsNullOrEmpty(table.Namespace) ? "" : "    ";

            if (!string.IsNullOrEmpty(table.Namespace))
            {
                text.Append("namespace ").Append(table.Namespace).Append("\n{\n");
            }

            text.Append(indent).Append("public class ").Append(table.ClassName).Append(" : global::Resource.BaseResourceModule\n")
                .Append(indent).Append("{\n")
                .Append(indent).Append("    public const string Id = ").Append(Literal(table.ModuleId)).Append(";\n");

            for (int index = 0; index < rows.Count; index++)
            {
                Row row = rows[index];
                string typeName = row.Type == ResourceType.GameObject ? "GameObject" : row.Type.ToString();
                text.Append("\n").Append(indent).Append("    public global::UnityEngine.").Append(typeName).Append(" ")
                    .Append(row.Name).Append(" => GetResource<global::UnityEngine.").Append(typeName).Append(">(")
                    .Append(index + 1).Append(");\n");
            }

            text.Append("\n").Append(indent).Append("    public override string GetName()\n")
                .Append(indent).Append("    {\n")
                .Append(indent).Append("        return Id;\n")
                .Append(indent).Append("    }\n\n")
                .Append(indent).Append("    protected override void RecordAllResourceInfos()\n")
                .Append(indent).Append("    {\n");

            for (int index = 0; index < rows.Count; index++)
            {
                text.Append(indent).Append("        AddResourceInfo(global::Resource.ResourceType.").Append(rows[index].Type)
                    .Append(", ").Append(index + 1).Append(", ").Append(Literal(rows[index].Address)).Append(");\n");
            }

            text.Append(indent).Append("    }\n").Append(indent).Append("}\n");

            if (!string.IsNullOrEmpty(table.Namespace))
            {
                text.Append("}\n");
            }

            return text.ToString();
        }

        private static bool IsOwnedAndUnmodified(string path, string sourceGuid, out string error)
        {
            string existing = Read(path);
            string expectedHeader = Header + OwnerHeader + sourceGuid + "\n" + HashHeader;

            if (!existing.StartsWith(expectedHeader, StringComparison.Ordinal))
            {
                error = "refusing to overwrite a handwritten file or another table's output: " + path;
                return false;
            }

            int hashEnd = existing.IndexOf('\n', expectedHeader.Length);

            if (hashEnd < 0 || hashEnd + 1 >= existing.Length || existing[hashEnd + 1] != '\n' ||
                existing.Substring(expectedHeader.Length, hashEnd - expectedHeader.Length) != Hash(existing.Substring(hashEnd + 2)))
            {
                error = "generated file was edited. Restore its generated version or move it aside before regenerating: " + path;
                return false;
            }

            error = null;
            return true;
        }

        private static bool ValidIdentifier(string value)
        {
            return !string.IsNullOrEmpty(value) && Identifier.IsMatch(value) && !Keywords.Contains(value);
        }

        private static bool ValidDottedIdentifier(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return false;
            }

            foreach (string part in value.Split('.'))
            {
                if (!ValidIdentifier(part))
                {
                    return false;
                }
            }

            return true;
        }

        private static string Literal(string value)
        {
            var text = new StringBuilder("\"");

            foreach (char character in value)
            {
                if (character == '\\' || character == '"')
                {
                    text.Append('\\').Append(character);
                }
                else if (character < ' ' || character > '~')
                {
                    text.Append("\\u").Append(((int)character).ToString("x4"));
                }
                else
                {
                    text.Append(character);
                }
            }

            return text.Append('"').ToString();
        }

        private static string Hash(string value)
        {
            using (var sha = SHA256.Create())
            {
                return BitConverter.ToString(sha.ComputeHash(Utf8.GetBytes(value))).Replace("-", "").ToLowerInvariant();
            }
        }

        private static string Read(string path)
        {
            string text = File.ReadAllText(path, Utf8);
            return text.Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static string Describe(ResourceModuleTable table)
        {
            return table == null ? "Resource module table" : AssetDatabase.GetAssetPath(table);
        }
    }

    public sealed class ResourceModuleTableBuildCheck : IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;

        public void OnPreprocessBuild(BuildReport report)
        {
            if (!ResourceModuleTableGenerator.ValidateOutputLocations(null, out string locationError))
            {
                throw new BuildFailedException(locationError);
            }

            foreach (string guid in AssetDatabase.FindAssets("t:ResourceModuleTable"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                var table = AssetDatabase.LoadAssetAtPath<ResourceModuleTable>(path);

                if (!ResourceModuleTableGenerator.ValidateGenerated(table, out string error))
                {
                    throw new BuildFailedException(error);
                }
            }
        }
    }
