using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace FrameworkConfig.Editor
{
    internal static partial class ConfigCompiler
    {
        internal const string GeneratedHeader = "// Generated by Framework Config. Do not edit.\n";

        public static Dictionary<string, string> Generate(ConfigTableModel model,
            IReadOnlyDictionary<string, ConfigTableModel> allModels, string gameNamespace)
        {
            var files = new Dictionary<string, string>(StringComparer.Ordinal);
            var name = model.Source.Name;
            var fields = RuntimeFields(model);
            var rows = new JArray();

            foreach (var sourceRow in model.Data)
            {
                var row = new JObject();

                foreach (var field in fields)
                {
                    object value;

                    if (field.Name == "Address" && SpecialFields.ContainsKey(name))
                    {
                        if (!model.Addresses.TryGetValue((string)sourceRow["Id"], out var address))
                        {
                            throw new InvalidOperationException(name + " assets have not been validated. Validate assets before generating.");
                        }

                        value = address;
                    }
                    else if (field.Type.StartsWith("ref:", StringComparison.Ordinal))
                    {
                        var target = allModels[field.Type.Substring(4)];

                        if (!TryValue((string)sourceRow[field.Name], target.Fields[0].Type, out value))
                        {
                            throw new InvalidOperationException(name + " references have not been validated.");
                        }
                    }
                    else
                    {
                        value = sourceRow[field.Name];
                    }

                    row.Add(field.Name, JToken.FromObject(value));
                }

                rows.Add(row);
            }

            var document = new JObject
            {
                ["_generatedBy"] = "Framework Config",
                ["Schema"] = 1,
                ["Rows"] = rows
            };
            files.Add("Resources/Config/" + gameNamespace + "/" + name + ".json", document.ToString(Formatting.Indented) + "\n");
            files.Add("Scripts/Generated/" + name + "Table.g.cs", GenerateTable(model, fields, allModels, gameNamespace));

            if (name == "UI" || name == "Scene")
            {
                files.Add("Scripts/Generated/" + name + "Name.g.cs", GenerateNames(model, gameNamespace));
            }

            if (name == "Resource")
            {
                foreach (var module in model.Data.GroupBy(row => (string)row["Module"]).OrderBy(group => group.Key, StringComparer.Ordinal))
                {
                    files.Add("Scripts/Generated/" + module.Key + "Resources.g.cs", GenerateModule(module.Key, module.ToList(), gameNamespace));
                }
            }

            return files;
        }

        public static Dictionary<string, string> GenerateBootstrap(IReadOnlyDictionary<string, ConfigTableModel> allModels,
            string gameNamespace)
        {
            var text = BeginFile(gameNamespace);
            Line(text, 1, "public static class GameConfig");
            Line(text, 1, "{");
            Line(text, 2, "public static void LoadAndRegister()");
            Line(text, 2, "{");

            if (allModels.ContainsKey("UI") || allModels.ContainsKey("Scene"))
            {
                Line(text, 3, "if (!global::Core.GameCore.IsReady)");
                Line(text, 3, "{");
                Line(text, 4, "throw new global::System.InvalidOperationException(\"Initialize GameCore before calling GameConfig.LoadAndRegister().\");");
                Line(text, 3, "}");
                Line(text);
            }

            foreach (var name in allModels.Keys.OrderBy(value => value, StringComparer.Ordinal))
            {
                Line(text, 3, name + "Table.Load();");
            }

            if (allModels.ContainsKey("UI"))
            {
                Line(text);
                Line(text, 3, "foreach (var row in UITable.All)");
                Line(text, 3, "{");
                Line(text, 4, "global::Core.GameCore.UI.RegisterUiData(new global::UI.UIData(row.Id, row.Address));");
                Line(text, 3, "}");
            }

            if (allModels.ContainsKey("Scene"))
            {
                Line(text);
                Line(text, 3, "foreach (var row in SceneTable.All)");
                Line(text, 3, "{");
                Line(text, 4, "global::Core.GameCore.Scene.RegisterScene(row.Id, row.Address);");
                Line(text, 3, "}");
            }

            Line(text, 2, "}");
            Line(text, 1, "}");
            Line(text, 0, "}");
            return new Dictionary<string, string>(StringComparer.Ordinal)
            {
                { "Scripts/Generated/GameConfig.g.cs", text.ToString() }
            };
        }

        private static string GenerateTable(ConfigTableModel model, List<ConfigField> fields,
            IReadOnlyDictionary<string, ConfigTableModel> allModels, string gameNamespace)
        {
            var name = model.Source.Name;
            var config = name + "Config";
            var idType = model.Fields[0].Type;
            var tableType = "global::FrameworkConfig.ConfigTable<" + idType + ", " + config + ">";
            var text = BeginFile(gameNamespace);
            Line(text, 1, "public sealed class " + config);
            Line(text, 1, "{");

            foreach (var field in fields)
            {
                Line(text, 2, "public " + RuntimeType(field, allModels) + " " + field.Name + " { get; }");
            }

            Line(text);
            var parameters = fields.Select((field, index) => RuntimeType(field, allModels) + " p" + index);
            Line(text, 2, "internal " + config + "(" + string.Join(", ", parameters) + ")");
            Line(text, 2, "{");

            for (var index = 0; index < fields.Count; index++)
            {
                Line(text, 3, "this." + fields[index].Name + " = p" + index + ";");
            }

            Line(text, 2, "}");
            Line(text, 1, "}");
            Line(text);
            Line(text, 1, "public static class " + name + "Table");
            Line(text, 1, "{");
            Line(text, 2, "[global::System.Serializable]");
            Line(text, 2, "private sealed class __Row");
            Line(text, 2, "{");

            foreach (var field in fields)
            {
                Line(text, 3, "public " + RuntimeType(field, allModels) + " " + field.Name + " = default;");
            }

            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "[global::System.Serializable]");
            Line(text, 2, "private sealed class __Data");
            Line(text, 2, "{");
            Line(text, 3, "public int Schema = default;");
            Line(text, 3, "public __Row[] Rows = default;");
            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "private static " + tableType + " _table;");
            Line(text, 2, "private static " + tableType + " Current => _table ?? throw new global::System.InvalidOperationException("
                + Literal(name + "Table is not loaded. Call GameConfig.LoadAndRegister() during game startup.") + ");");
            Line(text);
            Line(text, 2, "[global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            Line(text, 2, "private static void Reset()");
            Line(text, 2, "{");
            Line(text, 3, "_table = null;");
            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "public static global::System.Collections.Generic.IReadOnlyList<" + config + "> All => Current.All;");
            Line(text);
            Line(text, 2, "public static " + config + " Get(" + idType + " id)");
            Line(text, 2, "{");
            Line(text, 3, "return Current.Get(id);");
            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "public static bool TryGet(" + idType + " id, out " + config + " row)");
            Line(text, 2, "{");
            Line(text, 3, "return Current.TryGet(id, out row);");
            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "public static void Load()");
            Line(text, 2, "{");
            Line(text, 3, "_table = null;");
            Line(text, 3, "var data = global::FrameworkConfig.ConfigData.LoadJson<__Data>(" + Literal("Config/" + gameNamespace + "/" + name) + ");");
            Line(text);
            Line(text, 3, "if (data.Schema != 1 || data.Rows == null)");
            Line(text, 3, "{");
            Line(text, 4, "throw new global::System.InvalidOperationException(" + Literal(name + " config schema is invalid. Update config again.") + ");");
            Line(text, 3, "}");
            Line(text);
            Line(text, 3, "var rows = new global::System.Collections.Generic.List<" + config + ">(data.Rows.Length);");
            Line(text);
            Line(text, 3, "foreach (var row in data.Rows)");
            Line(text, 3, "{");
            Line(text, 4, "rows.Add(new " + config + "(" + string.Join(", ", fields.Select(field => "row." + field.Name)) + "));");
            Line(text, 3, "}");
            Line(text);
            Line(text, 3, "_table = new " + tableType + "(rows, row => row.Id);");
            Line(text, 2, "}");
            Line(text, 1, "}");
            Line(text, 0, "}");
            return text.ToString();
        }

        private static string GenerateNames(ConfigTableModel model, string gameNamespace)
        {
            var text = BeginFile(gameNamespace);
            Line(text, 1, "public static class " + model.Source.Name + "Name");
            Line(text, 1, "{");

            foreach (var id in model.Data.Select(row => (string)row["Id"]).OrderBy(value => value, StringComparer.Ordinal))
            {
                Line(text, 2, "public const string " + id + " = " + Literal(id) + ";");
            }

            Line(text, 1, "}");
            Line(text, 0, "}");
            return text.ToString();
        }

        private static string GenerateModule(string module, List<Dictionary<string, object>> sourceRows,
            string gameNamespace)
        {
            var rows = sourceRows.OrderBy(row => (string)row["Id"], StringComparer.Ordinal).ToList();
            var text = BeginFile(gameNamespace);
            Line(text, 1, "public sealed class " + module + "Resources : global::Resource.BaseResourceModule");
            Line(text, 1, "{");
            Line(text, 2, "public const string Id = " + Literal(gameNamespace + "." + module) + ";");
            Line(text);

            for (var index = 0; index < rows.Count; index++)
            {
                var row = rows[index];
                var type = (string)row["Type"] == "Prefab" ? "GameObject" : (string)row["Type"];
                Line(text, 2, "public global::UnityEngine." + type + " " + row["Id"]
                    + " => GetResource<global::UnityEngine." + type + ">(" + (index + 1).ToString(CultureInfo.InvariantCulture) + ");");
            }

            Line(text);
            Line(text, 2, "public override string GetName()");
            Line(text, 2, "{");
            Line(text, 3, "return Id;");
            Line(text, 2, "}");
            Line(text);
            Line(text, 2, "protected override void RecordAllResourceInfos()");
            Line(text, 2, "{");

            for (var index = 0; index < rows.Count; index++)
            {
                var row = rows[index];
                var type = (string)row["Type"] == "Prefab" ? "GameObject" : (string)row["Type"];
                Line(text, 3, "AddResourceInfo(global::Resource.ResourceType." + type + ", "
                    + (index + 1).ToString(CultureInfo.InvariantCulture) + ", ResourceTable.Get(" + Literal((string)row["Id"]) + ").Address);");
            }

            Line(text, 2, "}");
            Line(text, 1, "}");
            Line(text, 0, "}");
            return text.ToString();
        }

        private static List<ConfigField> RuntimeFields(ConfigTableModel model)
        {
            var special = SpecialFields.ContainsKey(model.Source.Name);
            var fields = model.Fields.Where(field => !special || field.Name != "Name").ToList();

            if (special)
            {
                fields.Add(new ConfigField { Name = "Address", Type = "string" });
            }

            return fields;
        }

        private static string RuntimeType(ConfigField field, IReadOnlyDictionary<string, ConfigTableModel> models)
        {
            return field.Type.StartsWith("ref:", StringComparison.Ordinal)
                ? models[field.Type.Substring(4)].Fields[0].Type : field.Type;
        }

        private static string Literal(string value)
        {
            return JsonConvert.SerializeObject(value, Formatting.None, new JsonSerializerSettings
            {
                StringEscapeHandling = StringEscapeHandling.EscapeNonAscii
            });
        }

        private static StringBuilder BeginFile(string gameNamespace)
        {
            return new StringBuilder(GeneratedHeader).Append("\nnamespace ").Append(gameNamespace).Append("\n{\n");
        }

        private static void Line(StringBuilder text, int indent = 0, string value = "")
        {
            if (value.Length > 0)
            {
                text.Append(' ', indent * 4).Append(value);
            }

            text.Append('\n');
        }
    }
