    public static class UITableGenerator
    {
        private const string Header = "// Generated by UITableGenerator. Do not edit.\n";
        private const string OwnerHeader = "// Source GUID: ";
        private const string HashHeader = "// Body SHA256: ";
        private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false);
        private static readonly Regex Identifier = new Regex("\\A[A-Za-z_][A-Za-z0-9_]*\\z");
        private static readonly HashSet<string> Keywords = new HashSet<string>(
            ("abstract as base bool break byte case catch char checked class const continue decimal " +
             "default delegate do double else enum event explicit extern false finally fixed float for " +
             "foreach goto if implicit in int interface internal is lock long namespace new null object " +
             "operator out override params private protected public readonly ref return sbyte sealed short " +
             "sizeof stackalloc static string struct switch this throw true try typeof uint ulong " +
             "unchecked unsafe ushort using virtual void volatile while add alias and ascending async " +
             "await by descending dynamic equals file from get global group init into join let managed " +
             "nameof nint not notnull nuint on or orderby partial record remove required scoped select " +
             "set unmanaged value var when where with yield __arglist __makeref __reftype __refvalue").Split(' '), StringComparer.Ordinal);

        public static bool Generate(UITable table)
        {
            if (!Validate(table, out string outputPath, out string content, out string error))
            {
                Debug.LogError(error, table);
                return false;
            }

            string temporaryPath = null;

            try
            {
                if (File.Exists(outputPath))
                {
                    if (!IsOwnedAndUnmodified(outputPath, AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table)), out error))
                    {
                        Debug.LogError(Describe(table) + ": " + error, table);
                        return false;
                    }

                    if (Read(outputPath) == content)
                    {
                        Debug.Log("UI table is already up to date: " + outputPath, table);
                        return true;
                    }
                }

                Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
                temporaryPath = outputPath + "." + Guid.NewGuid().ToString("N") + ".tmp";
                File.WriteAllText(temporaryPath, content, Utf8);

                if (File.Exists(outputPath))
                {
                    File.Replace(temporaryPath, outputPath, null);
                }
                else
                {
                    File.Move(temporaryPath, outputPath);
                }

                AssetDatabase.ImportAsset(outputPath);
                Debug.Log("Generated UI table: " + outputPath, table);
                return true;
            }
            catch (Exception exception)
            {
                Debug.LogError(Describe(table) + ": could not write generated code. " + exception.Message, table);
                return false;
            }
            finally
            {
                if (temporaryPath != null && File.Exists(temporaryPath))
                {
                    File.Delete(temporaryPath);
                }
            }
        }

        public static bool ValidateGenerated(UITable table, out string error)
        {
            if (!Validate(table, out string outputPath, out string content, out error))
            {
                return false;
            }

            try
            {
                if (!File.Exists(outputPath))
                {
                    error = Describe(table) + ": generated code is missing. Click Validate and Generate.";
                    return false;
                }

                if (!IsOwnedAndUnmodified(outputPath, AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table)), out error))
                {
                    error = Describe(table) + ": " + error;
                    return false;
                }

                if (Read(outputPath) != content)
                {
                    error = Describe(table) + ": generated code is out of date. Click Validate and Generate.";
                    return false;
                }

                error = null;
                return true;
            }
            catch (Exception exception)
            {
                error = Describe(table) + ": could not read generated code. " + exception.Message;
                return false;
            }
        }

        public static bool Validate(UITable table, out string outputPath, out string content, out string error)
        {
            outputPath = null;
            content = null;
            error = null;
            string source = Describe(table);

            try
            {
                string assetPath = AssetDatabase.GetAssetPath(table);
                const string suffix = "/Editor/Tables/UI.asset";

                if (table == null || !assetPath.StartsWith("Assets/", StringComparison.Ordinal) ||
                    !assetPath.EndsWith(suffix, StringComparison.Ordinal))
                {
                    throw new InvalidOperationException("save this table at <game root>/Editor/Tables/UI.asset inside Assets.");
                }

                string gameRoot = assetPath.Substring(0, assetPath.Length - suffix.Length);

                if (!ValidIdentifier(table.ClassName) || table.ClassName == "RegisterAll")
                {
                    throw new InvalidOperationException("ClassName must be a C# identifier and cannot be a keyword or RegisterAll.");
                }

                if (!string.IsNullOrEmpty(table.Namespace) && !ValidDottedIdentifier(table.Namespace))
                {
                    throw new InvalidOperationException("Namespace must contain C# identifiers separated by dots, or be empty.");
                }

                var otherTables = new List<UITable>();

                foreach (string guid in AssetDatabase.FindAssets("t:UITable"))
                {
                    string otherPath = AssetDatabase.GUIDToAssetPath(guid);
                    var other = AssetDatabase.LoadAssetAtPath<UITable>(otherPath);

                    if (other == null || other == table)
                    {
                        continue;
                    }

                    otherTables.Add(other);

                    if (other.ClassName == table.ClassName &&
                        string.Equals(other.Namespace ?? "", table.Namespace ?? "", StringComparison.Ordinal))
                    {
                        throw new InvalidOperationException("Namespace/ClassName is already used by another table: " + otherPath);
                    }
                }

                if (!ValidDottedIdentifier(table.IdPrefix))
                {
                    throw new InvalidOperationException("IdPrefix must contain identifiers separated by dots, for example MyGame.");
                }

                if (table.Entries == null || table.Entries.Count == 0)
                {
                    throw new InvalidOperationException("Entries cannot be empty.");
                }

                var settings = AddressableAssetSettingsDefaultObject.Settings;

                if (settings == null)
                {
                    throw new InvalidOperationException("Addressables settings are missing. Configure Addressables before generating.");
                }

                var assets = new List<AddressableAssetEntry>();
                settings.GetAllAssets(assets, false, group =>
                {
                    var schema = group.GetSchema<BundledAssetGroupSchema>();
                    return schema != null && schema.IncludeInBuild && schema.IncludeAddressInCatalog;
                });

                var names = new HashSet<string>(StringComparer.Ordinal);
                var prefabs = new HashSet<string>(StringComparer.Ordinal);
                var addresses = new List<string>();

                for (int index = 0; index < table.Entries.Count; index++)
                {
                    UITable.Entry entry = table.Entries[index];
                    string row = "Entry " + (index + 1) + ": ";

                    if (entry == null || !ValidIdentifier(entry.Name))
                    {
                        throw new InvalidOperationException(row + "Name must be a C# identifier and cannot be a keyword.");
                    }

                    if (entry.Name == "RegisterAll" || entry.Name == table.ClassName || !names.Add(entry.Name))
                    {
                        throw new InvalidOperationException(row + "Name is duplicated or conflicts with ClassName/RegisterAll: " + entry.Name);
                    }

                    foreach (UITable other in otherTables)
                    {
                        if (other.IdPrefix != table.IdPrefix || other.Entries == null)
                        {
                            continue;
                        }

                        for (int otherIndex = 0; otherIndex < other.Entries.Count; otherIndex++)
                        {
                            UITable.Entry otherEntry = other.Entries[otherIndex];

                            if (otherEntry != null && otherEntry.Name == entry.Name)
                            {
                                throw new InvalidOperationException(row + "UI ID " + table.IdPrefix + "." + entry.Name +
                                    " is already used by " + AssetDatabase.GetAssetPath(other) + " (Entry " + (otherIndex + 1) + ").");
                            }
                        }
                    }

                    string prefabPath = AssetDatabase.GetAssetPath(entry.Prefab);

                    if (entry.Prefab == null || !AssetDatabase.Contains(entry.Prefab) ||
                        !PrefabUtility.IsPartOfPrefabAsset(entry.Prefab) ||
                        !prefabPath.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase) ||
                        entry.Prefab.transform.parent != null ||
                        entry.Prefab.GetComponents<UIBase>().Length != 1)
                    {
                        throw new InvalidOperationException(row + "Prefab must reference the single UIBase component on a saved prefab root.");
                    }

                    string prefabGuid = AssetDatabase.AssetPathToGUID(prefabPath);

                    if (!prefabs.Add(prefabGuid))
                    {
                        throw new InvalidOperationException(row + "Prefab is used by another entry: " + prefabPath);
                    }

                    string address = null;

                    foreach (AddressableAssetEntry asset in assets)
                    {
                        if (asset.guid != prefabGuid || asset.AssetPath != prefabPath || string.IsNullOrWhiteSpace(asset.address))
                        {
                            continue;
                        }

                        if (address != null && address != asset.address)
                        {
                            throw new InvalidOperationException(row + "Prefab has multiple effective Addressables addresses: " + prefabPath);
                        }

                        address = asset.address;
                    }

                    if (address == null)
                    {
                        throw new InvalidOperationException(row + "Prefab has no loadable Addressables address. Check its group, Include in Build and Include Addresses in Catalog: " + prefabPath);
                    }

                    foreach (AddressableAssetEntry asset in assets)
                    {
                        if (asset.address == address && asset.guid != prefabGuid)
                        {
                            throw new InvalidOperationException(row + "Addressables address is shared by another asset: " + address);
                        }
                    }

                    addresses.Add(address);
                }

                outputPath = gameRoot + "/Scripts/Generated/" + table.ClassName + ".g.cs";
                string body = BuildBody(table, addresses);
                content = Header + OwnerHeader + AssetDatabase.AssetPathToGUID(assetPath) + "\n" +
                    HashHeader + Hash(body) + "\n\n" + body;
                return true;
            }
            catch (Exception exception)
            {
                error = source + ": " + exception.Message;
                return false;
            }
        }

        private static string BuildBody(UITable table, List<string> addresses)
        {
            var text = new StringBuilder();
            string indent = string.IsNullOrEmpty(table.Namespace) ? "" : "    ";

            if (!string.IsNullOrEmpty(table.Namespace))
            {
                text.Append("namespace ").Append(table.Namespace).Append("\n{\n");
            }

            text.Append(indent).Append("public static class ").Append(table.ClassName).Append("\n")
                .Append(indent).Append("{\n");

            foreach (UITable.Entry entry in table.Entries)
            {
                text.Append(indent).Append("    public const string ").Append(entry.Name).Append(" = ")
                    .Append(Literal(table.IdPrefix + "." + entry.Name)).Append(";\n");
            }

            text.Append("\n").Append(indent).Append("    public static void RegisterAll()\n")
                .Append(indent).Append("    {\n");

            for (int index = 0; index < table.Entries.Count; index++)
            {
                text.Append(indent).Append("        global::Core.GameCore.UI.RegisterUiData(new global::UI.UIData(\n")
                    .Append(indent).Append("            ").Append(table.Entries[index].Name).Append(", ")
                    .Append(Literal(addresses[index])).Append("));\n");

                if (index < table.Entries.Count - 1)
                {
                    text.Append("\n");
                }
            }

            text.Append(indent).Append("    }\n").Append(indent).Append("}\n");

            if (!string.IsNullOrEmpty(table.Namespace))
            {
                text.Append("}\n");
            }

            return text.ToString();
        }

        private static bool IsOwnedAndUnmodified(string path, string sourceGuid, out string error)
        {
            string existing = Read(path);
            string expectedHeader = Header + OwnerHeader + sourceGuid + "\n" + HashHeader;

            if (!existing.StartsWith(expectedHeader, StringComparison.Ordinal))
            {
                error = "refusing to overwrite a handwritten file or another table's output: " + path;
                return false;
            }

            int hashEnd = existing.IndexOf('\n', expectedHeader.Length);

            if (hashEnd < 0 || hashEnd + 1 >= existing.Length || existing[hashEnd + 1] != '\n' ||
                existing.Substring(expectedHeader.Length, hashEnd - expectedHeader.Length) != Hash(existing.Substring(hashEnd + 2)))
            {
                error = "generated file was edited. Restore its generated version or move it aside before regenerating: " + path;
                return false;
            }

            error = null;
            return true;
        }

        private static bool ValidIdentifier(string value)
        {
            return !string.IsNullOrEmpty(value) && Identifier.IsMatch(value) && !Keywords.Contains(value);
        }

        private static bool ValidDottedIdentifier(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return false;
            }

            foreach (string part in value.Split('.'))
            {
                if (!ValidIdentifier(part))
                {
                    return false;
                }
            }

            return true;
        }

        private static string Literal(string value)
        {
            var text = new StringBuilder("\"");

            foreach (char character in value)
            {
                if (character == '\\' || character == '"')
                {
                    text.Append('\\').Append(character);
                }
                else if (character < ' ' || character > '~')
                {
                    text.Append("\\u").Append(((int)character).ToString("x4"));
                }
                else
                {
                    text.Append(character);
                }
            }

            return text.Append('"').ToString();
        }

        private static string Hash(string value)
        {
            using (var sha = SHA256.Create())
            {
                return BitConverter.ToString(sha.ComputeHash(Utf8.GetBytes(value))).Replace("-", "").ToLowerInvariant();
            }
        }

        private static string Read(string path)
        {
            string text = File.ReadAllText(path, Utf8);
            return text.Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static string Describe(UITable table)
        {
            return table == null ? "UI table" : AssetDatabase.GetAssetPath(table);
        }
    }

    public sealed class UITableBuildCheck : IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;

        public void OnPreprocessBuild(BuildReport report)
        {
            foreach (string guid in AssetDatabase.FindAssets("t:UITable"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                var table = AssetDatabase.LoadAssetAtPath<UITable>(path);

                if (!UITableGenerator.ValidateGenerated(table, out string error))
                {
                    throw new BuildFailedException(error);
                }
            }
        }
    }
}
